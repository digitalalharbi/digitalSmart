<?php

declare(strict_types=1);

namespace App\Application\Presentation\Query;

use App\Application\Analytics\Contract\VisibilityResolver;
use App\Application\Analytics\DTO\AnalyticsFilters;
use App\Application\Client\Contract\ClientVisibility;
use App\Application\Intelligence\Query\Analyse;
use App\Application\Presentation\DTO\Deck;
use App\Application\Presentation\DTO\Slide;
use App\Application\Presentation\Service\DeckFromReport;
use App\Application\Reporting\DTO\ReportDefinition;
use App\Application\Reporting\DTO\SavedReport;
use App\Application\Reporting\DTO\SectionDefinition;
use App\Application\Reporting\Query\RenderReport;
use App\Application\Shared\Contract\ActorContext;
use App\Application\Shared\Contract\AuthorizationGuard;
use App\Application\Shared\Contract\Clock;
use App\Application\Shared\Exception\ResourceNotFound;
use App\Domain\Access\Permission;
use App\Domain\Analytics\Dimension;
use App\Domain\Analytics\Metric;
use App\Domain\Presentation\DeckKind;
use App\Domain\Presentation\PresentationTheme;
use App\Domain\Presentation\SlideKind;
use App\Domain\Reporting\ComparisonMode;
use App\Domain\Reporting\ReportAudience;
use App\Domain\Reporting\SectionKind;

/**
 * Builds a deck from a client's own figures.
 *
 * **It composes a report and renders it.** The definition is assembled for the deck's own window, handed to
 * `RenderReport`, and the result turned into slides — so a deck reads exactly the same figures as the reporting
 * surface and the client portal, computed once by the same aggregation. A presentation generator with its own
 * analytics would be a second set of numbers to reconcile in front of a client.
 *
 * **The report is never saved.** Nothing in this product's reporting module gains a row because somebody
 * generated a deck; a deck is output, and a saved report is a document somebody chose to keep.
 *
 * **The commentary slide is the assistant's**, which is the composition worth having: the prose on the last slide
 * carries the same evidence, the same confidence rules and the same attribution as the assistant's own surface —
 * including, when a model wrote it, that a model wrote it. A deck whose commentary was generated by different
 * means would be a deck whose commentary nobody could check.
 *
 * **It renders client-safe, always.** A deck is a file that gets forwarded, and a deck carrying the agency's
 * internal note is one internal note away from a difficult conversation. The audience is passed explicitly to
 * `RenderReport`, so the note is never loaded on this path rather than loaded and dropped.
 */
final readonly class ComposeDeck
{
    /** What a headline slide carries. Six is the reporting module's own cap, and a slide's natural limit too. */
    private const array HEADLINE = [
        Metric::Spend,
        Metric::Impressions,
        Metric::Clicks,
        Metric::Ctr,
        Metric::Cpc,
        Metric::Conversions,
    ];

    /** Enough platforms to show the mix, few enough to read from the back of a room. */
    private const int ROW_LIMIT = 8;

    public function __construct(
        private RenderReport $render,
        private DeckFromReport $layout,
        private Analyse $analyse,
        private ClientVisibility $clients,
        private AuthorizationGuard $guard,
        private ActorContext $actor,
        private VisibilityResolver $visibility,
        private Clock $clock,
    ) {}

    public function __invoke(DeckKind $kind, string $clientId): Deck
    {
        $this->guard->ensure(Permission::ReportsView);

        if ($kind->isBuiltFromBudget()) {
            /*
             * The media plan is composed elsewhere, from a budget rather than from delivery. Refused here rather
             * than quietly answered with a performance deck wearing the wrong title.
             */
            throw ResourceNotFound::of('Deck');
        }

        $workspaceId = $this->actor->workspaceId()->value;
        $visible = $this->visibility->visibleProjectIds();

        if (! $this->clients->isVisible($workspaceId, $visible, $clientId)) {
            /* Not found rather than forbidden: existence across a tenant boundary is itself sensitive. */
            throw ResourceNotFound::of('Client');
        }

        $clients = $this->clients->visible($workspaceId, $visible);
        $clientName = $clients[$clientId] ?? '';

        $report = ($this->render)(
            $workspaceId,
            new SavedReport(
                /* No id: this report is output, and nothing in the reporting module gains a row for a deck. */
                id: '',
                definition: $this->definition($kind, $clientId, $clientName),
                clientName: $clientName,
                createdByName: null,
                createdAt: $this->clock->now(),
                updatedAt: $this->clock->now(),
            ),
            /* Explicit, so no future change can make a deck carry the agency's internal commentary. */
            ReportAudience::ClientSafe,
        );

        $slides = [
            new Slide(
                kind: SlideKind::Title,
                title: sprintf('%s — %s', $clientName, $kind->label()),
                lead: sprintf('%s to %s', $report->period->startDate(), $report->period->endDate()),
                notes: [sprintf('Prepared %s.', $this->clock->now()->format('j F Y'))],
            ),
            ...$this->layout->slides($report),
        ];

        $commentary = $this->commentary($clientId, $clientName, $kind);

        if ($commentary !== null) {
            $slides[] = $commentary;
        }

        return new Deck(
            kind: $kind,
            theme: PresentationTheme::provisional(),
            clientName: $clientName,
            title: sprintf('%s — %s', $clientName, $kind->label()),
            subtitle: sprintf('%s to %s', $report->period->startDate(), $report->period->endDate()),
            slides: $slides,
            source: $report->source,
            preparedAt: $this->clock->now(),
            isClientSafe: true,
        );
    }

    /**
     * The report this deck is.
     *
     * Composed rather than loaded, and the shape is the kind's: a weekly report is a scorecard, a trend and a
     * ranking; a monthly one adds the campaign table a client files; a closing report drops the comparison,
     * because there is nothing after an engagement to compare it with.
     */
    private function definition(DeckKind $kind, string $clientId, string $clientName): ReportDefinition
    {
        $sections = [
            new SectionDefinition(kind: SectionKind::Scorecard, metrics: self::HEADLINE),
            new SectionDefinition(kind: SectionKind::Trend, metrics: [Metric::Spend, Metric::Clicks]),
            new SectionDefinition(
                kind: SectionKind::Breakdown,
                /* Additive only: a ranking's rows are summed, and the shape refuses the rest anyway. */
                metrics: [Metric::Spend],
                dimension: Dimension::Provider,
            ),
        ];

        if ($kind !== DeckKind::WeeklyReport) {
            $sections[] = new SectionDefinition(
                kind: SectionKind::Table,
                metrics: [Metric::Spend, Metric::Clicks, Metric::Conversions],
                dimension: Dimension::Campaign,
                rowLimit: self::ROW_LIMIT,
            );
        }

        $window = $kind->window() ?? throw ResourceNotFound::of('Deck');

        return new ReportDefinition(
            name: sprintf('%s — %s', $clientName, $kind->label()),
            window: $window,
            comparison: $kind->comparesPeriods() ? ComparisonMode::PreviousPeriod : ComparisonMode::None,
            audience: ReportAudience::ClientSafe,
            filters: new AnalyticsFilters(clientId: $clientId),
            sections: $sections,
            clientId: $clientId,
        );
    }

    /**
     * The assistant's findings, as prose.
     *
     * Null when the reader may not run the assistant, rather than a slide composed by other means. A commentary
     * slide whose figures came from somewhere else would be a slide nobody could check against the rest of the
     * deck.
     */
    private function commentary(string $clientId, string $clientName, DeckKind $kind): ?Slide
    {
        if (! $this->guard->allows(Permission::AnalyticsView)) {
            return null;
        }

        $window = $kind->window();

        if ($window === null) {
            return null;
        }

        $analysis = ($this->analyse)($clientId, $clientName, $window->resolve($this->clock->now()));

        $paragraphs = array_values(array_filter(
            explode("\n\n", $analysis->narrative->text),
            static fn (string $paragraph): bool => trim($paragraph) !== '',
        ));

        if ($paragraphs === []) {
            return null;
        }

        return new Slide(
            kind: SlideKind::Commentary,
            title: SlideKind::Commentary->label(),
            lead: null,
            notes: [
                /*
                 * Who wrote it, on the slide. A paragraph composed by a language model and one assembled by the
                 * product are both legitimate; presenting one as the other is not, and a deck is read by somebody
                 * who was not in the room when it was made.
                 */
                $analysis->narrative->writtenBy === 'model'
                    ? sprintf('Commentary written by %s from the findings above.', $analysis->narrative->model ?? '')
                    : 'Commentary written by digitalSmart from the findings above.',
            ],
            paragraphs: $paragraphs,
        );
    }
}
